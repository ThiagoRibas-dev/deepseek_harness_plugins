/**
 * Gemini thought-signature capture and replay for the OpenAI-compatible API.
 *
 * Gemini 3 attaches an opaque signature to the first function call of each
 * step and requires it back on the same assistant tool call. pi-ai 0.85.1's
 * OpenAI-completions parser drops the `extra_content` field that carries it, so
 * the second request of a tool loop fails with `Function call is missing a
 * thought_signature`.
 *
 * The connector cannot change pi-ai's parser, but it controls the HTTP layer:
 * the member provider tees the SSE response, this module records each
 * `choices[].delta.tool_calls[].extra_content.google.thought_signature` by tool
 * call id, and `replayGeminiSignatures` puts it back on the assistant
 * `tool_calls[]` entry of the next request in `onPayload`.
 *
 * Signatures are scoped by member key (which carries the pool/member identity
 * and therefore its credential reference and endpoint). Gemini's signatures are
 * credential/account-scoped: a signature produced with one API key must not be
 * replayed to another, so `replayGeminiSignatures` requires the same member that
 * captured it. Rotation across members happens at turn boundaries, where
 * Gemini validates only the new turn.
 *
 * Signatures are process-local and bounded. A restart between steps loses them;
 * the session history then has an unsigned tool call, which Gemini rejects
 * (the current turn's first function call must carry its signature). Persisting
 * them across restarts would be a separate sidecar; it is not done here.
 *
 * @module @local/dsh-model-rotation/gemini-signatures
 */

/**
 * Documented placeholder that tells Gemini to skip signature validation for a
 * function call that was not generated by Gemini (for example, history from a
 * different model, or a call made with another key). Google describes it as a
 * last resort that can reduce model performance.
 */
export const DUMMY_SIGNATURE = 'skip_thought_signature_validator'

/** Signatures by member key and provider tool-call id. */
const signatures = new Map()

/** One member's signature key; a signature never crosses members. */
function keyOf(memberKey, callId) {
  return `${String(memberKey)}\u0000${String(callId)}`
}

/** Upper bound on retained signatures. */
const MAX_SIGNATURES = 2_000

/** Whether one member baseURL is Gemini's own OpenAI-compatible endpoint. */
export function isGeminiBaseURL(baseURL) {
  return typeof baseURL === 'string'
    && baseURL.includes('generativelanguage.googleapis.com')
}

/** Remember one signature, dropping the oldest when the bound is crossed. */
function remember(memberKey, id, signature) {
  if (typeof id !== 'string' || id.length === 0 || typeof signature !== 'string' || signature.length === 0) return
  signatures.set(keyOf(memberKey, id), signature)
  while (signatures.size > MAX_SIGNATURES) {
    const oldest = signatures.keys().next().value
    if (oldest === undefined) break
    signatures.delete(oldest)
  }
}

/**
 * Record signatures from one parsed OpenAI-compatible chunk or message.
 * @param payload - decoded SSE `data:` JSON.
 * @param memberKey - member that produced the response; signatures are scoped to it.
 */
export function recordGeminiChunk(payload, memberKey) {
  if (payload === null || typeof payload !== 'object') return
  const choices = Array.isArray(payload.choices) ? payload.choices : []
  for (const choice of choices) {
    if (choice === null || typeof choice !== 'object') continue
    const delta = choice.delta ?? choice.message
    if (delta === null || typeof delta !== 'object') continue
    const calls = Array.isArray(delta.tool_calls) ? delta.tool_calls : []
    for (const call of calls) {
      if (call === null || typeof call !== 'object') continue
      const signature = call.extra_content?.google?.thought_signature
      remember(memberKey, call.id, signature)
    }
  }
}

/**
 * Read one Gemini SSE body and record every tool-call signature it carries.
 * The stream is a tee branch; failures are contained so the client still gets
 * the original bytes.
 * @param stream - response body branch.
 * @param memberKey - member that produced the response.
 */
export async function captureGeminiResponse(stream, memberKey) {
  if (stream === null || typeof stream?.getReader !== 'function') return
  const reader = stream.getReader()
  const decoder = new TextDecoder()
  let buffer = ''
  try {
    while (true) {
      const { done, value } = await reader.read()
      if (done === true) break
      buffer += decoder.decode(value, { stream: true }).replaceAll('\r\n', '\n')
      let at = buffer.indexOf('\n\n')
      while (at >= 0) {
        const event = buffer.slice(0, at)
        buffer = buffer.slice(at + 2)
        for (const line of event.split('\n')) {
          if (!line.startsWith('data:')) continue
          const data = line.slice(5).trim()
          if (data.length === 0 || data === '[DONE]') continue
          try {
            recordGeminiChunk(JSON.parse(data), memberKey)
          } catch {
            // A partial or non-JSON event is not a signature-bearing chunk.
          }
        }
        at = buffer.indexOf('\n\n')
      }
    }
  } catch {
    // Tee inspection must never disturb the provider stream.
  } finally {
    try {
      reader.releaseLock()
    } catch {
      // The stream may already be closed.
    }
  }
}

/**
 * Put recorded signatures back on the assistant tool calls of one request body.
 * Mutates the body object the protocol just built; returns it for convenience.
 * @param body - OpenAI-compatible request body.
 * A recorded signature is preferred. When none exists for this member, the
 * documented `skip_thought_signature_validator` placeholder is used: this is
 * what makes history transferred from another model, a fresh key, or a
 * mid-turn failover pass validation. It skips signature validation and can
 * reduce model performance, so a real same-member signature always wins.
 *
 * @param memberKey - member that will receive the request; only its own
 *   signatures are replayed.
 * @returns the same body.
 */
export function replayGeminiSignatures(body, memberKey) {
  if (body === null || typeof body !== 'object' || !Array.isArray(body.messages)) return body
  for (const message of body.messages) {
    if (message === null || typeof message !== 'object' || message.role !== 'assistant') continue
    if (!Array.isArray(message.tool_calls)) continue
    for (const call of message.tool_calls) {
      if (call === null || typeof call !== 'object' || typeof call.id !== 'string') continue
      if (call.extra_content !== undefined) continue
      const signature = signatures.get(keyOf(memberKey, call.id)) ?? DUMMY_SIGNATURE
      call.extra_content = { google: { thought_signature: signature } }
    }
  }
  return body
}

/** Test hook: drop every remembered signature. */
export function resetGeminiSignatures() {
  signatures.clear()
}
